    public const string English = "en";
    public const string ChineseSimplified = "zh-CN";
    public const string ChineseEnglish = "zh-CN+en";

    public static readonly (string Code, string Name)[] Languages =
    [
        (English, "English"),
        (ChineseSimplified, "\u7b80\u4f53\u4e2d\u6587"),
        (ChineseEnglish, "\u4e2d\u6587 / English")
    ];

    public static string CurrentLanguage
    {
        get
        {
            try
            {
                return RainEd.Instance?.Preferences.Language ?? English;
            }
            catch
            {
                return English;
            }
        }
    }

    public static string LanguageName(string code)
    {
        foreach (var lang in Languages)
        {
            if (lang.Code == code)
                return lang.Name;
        }

        return code;
    }

    public static string T(string text)
    {
        var language = CurrentLanguage;

        if (language == English)
            return text;

        if (!ZhCn.TryGetValue(text, out var translated))
            return text;

        return language == ChineseEnglish ? $"{translated} / {text}" : translated;
    }

    public static string Asset(string text)
    {
        var language = CurrentLanguage;

        if (language == English)
            return text;

        var translated = ZhCn.TryGetValue(text, out var exact)
            ? exact
            : TranslateAssetWords(text);

        if (translated == text)
            return text;

        return language == ChineseEnglish ? $"{translated} / {text}" : translated;
    }

    public static string Combo(params string[] items)
        => string.Join('\0', items.Select(T)) + '\0';

    public static IEnumerable<string> GlyphSourceTexts()
    {
        foreach (var (_, name) in Languages)
            yield return name;

        foreach (var (_, target) in AssetWordTranslations)
            yield return target;

        foreach (var (_, target) in ZhCn)
            yield return target;
    }

    private static string TranslateAssetWords(string text)
    {
        if (string.IsNullOrWhiteSpace(text))
            return text;

        var parts = new List<string>();
        foreach (System.Text.RegularExpressions.Match match in System.Text.RegularExpressions.Regex.Matches(
            text,
            @"\d+[A-Z]+|[A-Z]{2,}(?=[A-Z][a-z]|\d|\b)|[A-Z]?[a-z]+|[A-Z]+|\d+"
        ))
        {
            parts.Add(TranslateAssetToken(match.Value));
        }

        return parts.Count == 0 ? text : string.Join(" ", parts);
    }

    private static string TranslateAssetToken(string token)
    {
        foreach (var (source, target) in AssetWordTranslations)
        {
            if (string.Equals(source, token, StringComparison.OrdinalIgnoreCase))
                return target;
        }

        if (int.TryParse(token, out _))
            return string.Concat(token.Select(ch => AssetDigitTranslations.GetValueOrDefault(ch, ch.ToString())));

        return token;
    }

